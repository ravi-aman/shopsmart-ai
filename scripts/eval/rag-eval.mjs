// Runs the golden question set against POST /api/ai/knowledge/ask and scores:
//   retrieval  — the cited source is the expected document/section
//   answer     — the answer contains the expected fact
//   refusal    — unanswerable questions come back LOW + followUpRequired
// Usage: node scripts/eval/rag-eval.mjs [baseUrl]   (default http://127.0.0.1:8080)
// Writes docs/rag-eval-results.md.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const base = process.argv[2] ?? 'http://127.0.0.1:8080'
const root = path.resolve(import.meta.dirname, '../..')
const golden = JSON.parse(readFileSync(path.join(import.meta.dirname, 'golden.json'), 'utf8'))

const anyOf = (value, expected) => expected.split('|').some((e) => e === value)

const rows = []
for (const g of golden) {
  let res
  for (;;) {
    res = await fetch(`${base}/api/ai/knowledge/ask`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ question: g.q, productId: g.productId }),
    })
    if (res.status !== 429) break
    console.log('      (rate limited — waiting for the next minute)')
    await new Promise((r) => setTimeout(r, 61_000 - (Date.now() % 60_000)))
  }
  const a = await res.json()
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${JSON.stringify(a)}`)
  const top = a.citations?.[0]
  let pass
  let retrieval = null
  let answer = null
  if (g.expectNotFound) {
    pass = a.confidence === 'LOW' && a.followUpRequired === true
  } else {
    retrieval = !!top && anyOf(top.document, g.doc) && anyOf(top.section, g.section)
    answer = a.confidence !== 'LOW' && a.answer.toLowerCase().includes(g.contains.toLowerCase())
    pass = retrieval && answer
  }
  rows.push({ ...g, pass, retrieval, answer, got: a })
  console.log(`${pass ? 'PASS' : 'FAIL'}  ${g.q}${pass ? '' : `\n      → ${a.confidence} | ${top ? `${top.document} › ${top.section}` : 'no source'} | ${a.answer.slice(0, 110)}`}`)
}

const answerable = rows.filter((r) => !r.expectNotFound)
const refusals = rows.filter((r) => r.expectNotFound)
const pct = (n, d) => (d === 0 ? '—' : `${Math.round((n / d) * 100)}%`)
const retrievalOk = answerable.filter((r) => r.retrieval).length
const answerOk = answerable.filter((r) => r.answer).length
const refusalOk = refusals.filter((r) => r.pass).length
const mode = rows.some((r) => r.got.aiAssisted) ? 'NVIDIA model (grounded generation)' : 'offline extractive mode (no NVIDIA key)'

const summary = [
  `Retrieval (correct document + section cited): ${retrievalOk}/${answerable.length} (${pct(retrievalOk, answerable.length)})`,
  `Answer contains the expected fact: ${answerOk}/${answerable.length} (${pct(answerOk, answerable.length)})`,
  `Unanswerable questions refused: ${refusalOk}/${refusals.length} (${pct(refusalOk, refusals.length)})`,
]
console.log(`\n${summary.join('\n')}\nMode: ${mode}`)

const md = `# RAG evaluation results

Generated by \`node scripts/eval/rag-eval.mjs\` against \`${base}\` on ${new Date().toISOString().slice(0, 10)}.
Mode: **${mode}**.

${summary.map((s) => `- ${s}`).join('\n')}

| # | Question | Expected source | Got | Confidence | Result |
|---|---|---|---|---|---|
${rows
  .map((r, i) => {
    const top = r.got.citations?.[0]
    const expected = r.expectNotFound ? '_not in policies_' : `${r.doc} › ${r.section}`
    const got = top ? `${top.document} › ${top.section}` : '—'
    return `| ${i + 1} | ${r.q} | ${expected} | ${got} | ${r.got.confidence} | ${r.pass ? '✅' : '❌'} |`
  })
  .join('\n')}
`
writeFileSync(path.join(root, 'docs', 'rag-eval-results.md'), md)
process.exit(rows.every((r) => r.pass) ? 0 : 1)
